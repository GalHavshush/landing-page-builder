BRAND_ALIASES = {
    "twitter": "x",
    "ig": "instagram",
    "fb": "facebook",
    "yt": "youtube",
    "wa": "whatsapp",
}

IconName = Literal[tuple(ICONS)]  # type: ignore[valid-type]


def _svg(body: str) -> Markup:
    return Markup(  # noqa: S704 - static strings above
        '<svg class="icon" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" '
        f'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{body}</svg>'
    )


def render_icon(name: str | None) -> Markup:
    if not name or name not in ICONS:
        return Markup("")
    return _svg(ICONS[name])


def render_brand_icon(name: str) -> Markup:
    """The logo for a social link called `name` (e.g. "Instagram"); a globe for unknown ones."""
    key = name.strip().lower()
    key = BRAND_ALIASES.get(key, key)
    return _svg(BRAND_ICONS.get(key) or ICONS["globe"])
